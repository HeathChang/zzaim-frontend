/** 경계 신호의 패턴 — **한 곳에만 둔다.**
 *
 *  같은 정규식을 두 곳에 두면 반드시 갈라진다. 신뢰도 산정(confidence)과
 *  경계 판정(segment)과 추출(extract)이 **같은 패턴을 본다**는 것이 전제다. */

export const CIRCLED = '①②③④⑤⑥⑦⑧⑨⑩'

/** 줄 시작의 문항 번호. `1.` `2)` */
export const NUM_RE = /^\s*(\d{1,2})\s*[.)]\s*/
/** 동그라미 선택지 */
export const CIR_RE = new RegExp(`^\\s*([${CIRCLED}])\\s*`)
/** 묶음 지시문 `[1~3]` — 지문 경계 */
export const RANGE_RE = /^\s*\[\s*(\d{1,2})\s*[~\-–]\s*(\d{1,2})\s*\]/
/** 배점 `[3점]` `(4점)` */
export const PTS_RE = /[[(]\s*(\d{1,2})\s*점\s*[\])]/
/** 상호참조 «위 3번과 관련하여» — 채번이 바뀌면 문장이 틀린다 */
export const XREF_RE = /(\d{1,2})\s*번/

/** 발문의 끝. 뒤에 배점이 붙는 경우가 많아 함께 허용한다.
 *  **이 목록이 휴리스틱의 약한 고리다** — 새 어미가 나오면 여기 더한다.
 *  코퍼스가 그것을 잡아 준다 (`segmentation.test.ts`). */
export const STEM_END =
  /(것은|것을|고르면|쓰시오|서술하시오|설명하시오|답하시오|무엇인가|값은|좌표는|넓이는|알맞은|원인은|역할은|조건은|목적은)[\s?.]*(?:[[(]\s*\d{1,2}\s*점\s*[\])])?\s*$/
